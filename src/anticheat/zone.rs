pub fn legacy_zone_anticheat(px: f32, py: f32, map_id: i8) -> bool {
    if map_id < 0 || map_id as usize >= MAP_ZONES.len() {
        return false;
    }
    let zones = MAP_ZONES[map_id as usize];
    let (px, py) = (px as f64, py as f64);
    zones.iter().any(|zone| {
        px >= zone.x && py >= zone.y && px <= zone.x + zone.width && py <= zone.y + zone.height
    })
}

pub fn zone_anticheat(px: f32, py: f32, map_id: i8) -> bool {
    super::physics::table()
        .get(map_id)
        .map(|map_physics| map_physics.out_of_bounds(px, py))
        .unwrap_or(false)
}
