/// The game's tile size. Every zone below is laid out in whole or fractional
/// tiles, so the numbers stay readable as "three tiles wide" instead of "384".
const TILE: f64 = 128.0;

#[derive(Clone, Copy, Debug)]
pub struct Zone {
    pub x: f64,
    pub y: f64,
    pub width: f64,
    pub height: f64,
}

/// Shorthand for one table row below. The tables are long enough that the full
/// struct literal on every line would bury the numbers that actually matter.
const fn zone(x: f64, y: f64, width: f64, height: f64) -> Zone {
    Zone { x, y, width, height }
}

