//! Skin colours (scr_palletes, scr_pallette_shifts). A skin replaces the "from"
//! colours of a character sprite with its "to" colours (shader shd_colour); the
//! server checks that a player's reported skin is one of these. Colours are
//! 0xRRGGBB, the same digits as the #rrggbb literals of the original.

use crate::core::player::{Character, ExeCharacter};

/// A demonized survivor's table is its character number plus this.
pub const PALETTE_DEMON: usize = 20;
/// An EXE character's table is its EXE number plus this.
pub const PALETTE_EXE: usize = 40;

pub struct Palette {
    pub from: &'static [u32],
    pub to: &'static [u32],
}

/// The skins of one character look.
pub struct PaletteTable {
    /// Character number, plus PALETTE_DEMON or PALETTE_EXE.
    pub table: usize,
    /// The "classic" and "eccentric" skins, in menu order.
    pub skins: [Palette; 2],
    /// The colours the "custom" skin shifts (in hue, or brightness for Exetior and Exeller).
    pub custom_colours: &'static [u32],
}

pub fn palette_table(table: usize) -> Option<&'static PaletteTable> {
    PALETTE_TABLES.iter().find(|candidate| candidate.table == table)
}

